package main

import (
	"bufio"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

var ecuHeading = regexp.MustCompile("^\\s*///\\s*\\S+\\s*\\[([0-9A-Fa-f]{1,2})\\]")
var dtcLine = regexp.MustCompile("^\\s*([0-9A-Fa-f]{6})\\s*->\\s*(.+?)\\s*$")

func (a *application) dtc(args []string) error {
	if len(args) < 2 || len(args) > 3 { return errors.New("usage: mgu dtc import|db|codes|csv|tables INPUT [OUTPUT]") }
	if err := loadDTCWords(filepath.Join(a.upstream, "kit", "tools", "german_words.txt")); err != nil { return err }
	source := absolute(args[1])
	var output string
	switch args[0] {
	case "import":
		output = filepath.Join(a.root, "apps", "dtc_scanner", "dtc_texts.js")
	case "db", "codes":
		output = a.dtcDirectory()
	case "csv":
		output = filepath.Join(a.root, "bmw-extracted", "dtc_tables")
	case "tables":
		output = filepath.Join(a.dtcDirectory(), "tables")
	default:
		return errors.New("usage: mgu dtc import|db|codes|csv|tables INPUT [OUTPUT]")
	}
	if len(args) == 3 { output = absolute(args[2]) }
	switch args[0] {
	case "import": return a.importDTCExport(source, output)
	case "db": return a.importDTCDatabase(source, output)
	case "codes": return a.importDTCCodes(source, output)
	case "csv": return a.importDTCCSV(source, output)
	case "tables": return a.importDTCTables(source, output)
	}
	return nil
}

func (a *application) importDTCExport(source, out string) error {
	if source == out { return errors.New("input and output must be different files") }
	file, err := os.Open(source)
	if err != nil { return err }
	defer file.Close()
	scanner := bufio.NewScanner(file)
	scanner.Buffer(make([]byte, 65536), 4*1024*1024)
	address := ""
	texts := map[string]string{}
	for scanner.Scan() {
		line := scanner.Text()
		if match := ecuHeading.FindStringSubmatch(line); match != nil {
			address = strings.ToUpper(match[1])
			if len(address) == 1 { address = "0" + address }
			continue
		}
		if match := dtcLine.FindStringSubmatch(line); match != nil && address != "" {
			description := strings.TrimSpace(match[2])
			if !strings.HasPrefix(strings.ToLower(description), "no description") && isEnglishDTC(description) { texts[address+":"+strings.ToUpper(match[1])] = hmiText(description) }
		}
	}
	if err := scanner.Err(); err != nil { return err }
	data, err := json.MarshalIndent(texts, "", " ")
	if err != nil { return err }
	header := "'use strict';\n// generated by mgu dtc import from " + hmiText(filepath.Base(source)) + " - fault texts for one car, not in git\nmodule.exports = "
	if err := writeFile(out, append(append([]byte(header), data...), []byte(";\n")...), 0644); err != nil { return err }
	fmt.Fprintf(a.out, "%d fault texts -> %s\n", len(texts), out)
	return nil
}

